# ── 合并去重（模糊匹配） ─────────────────────────────────
def normalize(word):
    """去除标点符号和空格，用于模糊去重"""
    import re
    return re.sub(r'[^\u4e00-\u9fa5a-zA-Z0-9]', '', word).lower()

all_items = []
seen = set()

for w in baidu_raw:
    n = normalize(w)
    if n and n not in seen:
        seen.add(n)
        all_items.append({"word": w, "source": "百度"})

for w in weibo_raw:
    n = normalize(w)
    # 与百度条目做更宽松的包含去重
    is_dup = False
    for s in list(seen):
        if n in s or s in n:
            is_dup = True
            break
    if n and not is_dup:
        seen.add(n)
        all_items.append({"word": w, "source": "微博"})

